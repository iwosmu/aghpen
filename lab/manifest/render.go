// yq quotes a scalar for YAML. JSON strings are valid YAML double-quoted
// strings. "$" is doubled because compose interpolates variables.
func yq(s string) string {
	b, _ := json.Marshal(strings.ReplaceAll(s, "$", "$$"))
	// json.Marshal escapes <, > and & for HTML; undo that for readability.
	r := strings.NewReplacer(`\u003c`, "<", `\u003e`, ">", `\u0026`, "&")
	return r.Replace(string(b))
}

func yList(items []string) string {
	q := make([]string, len(items))
	for i, s := range items {
		q[i] = yq(s)
	}
	return "[" + strings.Join(q, ", ") + "]"
}

func configName(container string, i int) string {
	return fmt.Sprintf("%s-cfg-%d", container, i)
}

// Compose renders lab/docker-compose.yml.
func (l *Lab) Compose() string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	w("# Czujka test lab. GENERATED by \"go run ./lab/gen\" from lab/manifest. Do not edit.\n")
	w("# One bridge network %s with fixed addresses. See lab/README.md.\n", Network)
	w("name: czujka-lab\n\nnetworks:\n  lab:\n    name: czujka-lab\n    driver: bridge\n    ipam:\n      config:\n        - subnet: %s\n          gateway: %s\n\n", Network, Gateway)
	w("volumes:\n  lab-state: {}\n\n")

	w("configs:\n")
	for _, c := range l.Containers {
		for i, cf := range c.Configs {
			w("  %s:\n    content: |\n", configName(c.Name, i))
			for _, line := range strings.Split(strings.TrimRight(strings.ReplaceAll(cf.Content, "$", "$$"), "\n"), "\n") {
				if line == "" {
					w("\n")
				} else {
					w("      %s\n", line)
				}
			}
		}
	}
	w("\nservices:\n")
	built := map[string]bool{}
	for _, c := range l.Containers {
		w("  # %s — %s\n", c.IP, c.Desc)
		w("  %s:\n", c.Name)
		w("    image: %s\n", yq(c.Image))
		if c.Build != nil {
			// Several services share one image; only the first one builds it.
			if !built[c.Image] {
				built[c.Image] = true
				w("    build:\n      context: %s\n", yq("./"+c.Build.Context))
				if c.Build.Dockerfile != "" {
					w("      dockerfile: %s\n", yq(c.Build.Dockerfile))
				}
				if len(c.Build.Args) > 0 {
					w("      args:\n")
					for _, a := range c.Build.Args {
						w("        %s: %s\n", a[0], yq(a[1]))
					}
				}
			} else {
				w("    pull_policy: never\n")
			}
		}
		w("    hostname: %s\n", yq(c.Name))
		if c.In != nil && !c.InState("t0") {
			w("    profiles: [\"later\"]\n")
		}
		w("    networks:\n      lab:\n        ipv4_address: %s\n", c.IP)
		if c.DNS != "" {
			w("    dns: [%s]\n", yq(c.DNS))
		}
		if len(c.Entrypoint) > 0 {
			w("    entrypoint: %s\n", yList(c.Entrypoint))
		}
		if len(c.Command) > 0 {
			w("    command: %s\n", yList(c.Command))
		}
		if c.Init {
			w("    init: true\n")
		}
		if c.User != "" {
			w("    user: %s\n", yq(c.User))
		}
		env := append([][2]string(nil), c.Env...)
		if len(env) > 0 {
			w("    environment:\n")
			for _, e := range env {
				w("      %s: %s\n", e[0], yq(e[1]))
			}
		}
		if len(c.Configs) > 0 {
			w("    configs:\n")
			for i, cf := range c.Configs {
				mode := cf.Mode
				if mode == "" {
					mode = "0444"
				}
				w("      - source: %s\n        target: %s\n        mode: %s\n", configName(c.Name, i), yq(cf.Target), mode)
			}
		}
		switch {
		case c.StateRW:
			w("    volumes: [\"lab-state:/lab-state\"]\n")
		case c.Sim != nil:
			w("    volumes: [\"lab-state:/lab-state:ro\"]\n")
		}
		if len(c.CapAdd) > 0 {
			w("    cap_add: %s\n", yList(c.CapAdd))
		}
		if len(c.Sysctls) > 0 {
			w("    sysctls:\n")
			for _, s := range c.Sysctls {
				w("      %s: %s\n", s[0], yq(s[1]))
			}
		}
		if len(c.Tmpfs) > 0 {
			w("    tmpfs: %s\n", yList(c.Tmpfs))
		}
		mem := c.MemMB
		if mem == 0 {
			mem = 128
		}
		w("    mem_limit: %dm\n", mem)
		if len(c.DependsOn) > 0 {
			w("    depends_on:\n")
			for _, d := range c.DependsOn {
				w("      %s:\n        condition: service_healthy\n", d)
			}
		}
		sp := c.Health.StartPeriod
		if sp == "" {
			sp = "60s"
		}
		w("    healthcheck:\n      test: [\"CMD-SHELL\", %s]\n      interval: 20s\n      timeout: 8s\n      retries: 6\n      start_period: %s\n      start_interval: 2s\n", yq(c.Health.Test), sp)
		w("    stop_grace_period: 3s\n")
		w("    labels:\n      czujka.lab.group: %s\n\n", yq(c.Group))
	}
	return b.String()
}

// StatesScript renders lab/generated/states.sh, read by lab/scenario.sh.
func (l *Lab) StatesScript() string {
	var b strings.Builder
	b.WriteString("# GENERATED by \"go run ./lab/gen\" from lab/manifest. Do not edit.\n")
	b.WriteString("# For every lab state: conditional services to stop and to start.\n")
	b.WriteString("LAB_STATES=\"" + strings.Join(labcfg.States, " ") + "\"\n")
	for _, st := range labcfg.States {
		stop, start := l.StateLists(st)
		fmt.Fprintf(&b, "STOP_%s=\"%s\"\nSTART_%s=\"%s\"\n", st, strings.Join(stop, " "), st, strings.Join(start, " "))
		var up []string
		for _, c := range l.Containers {
			if c.InState(st) {
				up = append(up, c.Name)
			}
		}
		fmt.Fprintf(&b, "UP_%s=\"%s\"\n", st, strings.Join(up, " "))
	}
	var unstable []string
	for _, c := range l.Containers {
		if c.Avail != nil {
			unstable = append(unstable, c.Name)
		}
	}
	fmt.Fprintf(&b, "UNSTABLE=\"%s\"\n", strings.Join(unstable, " "))
	return b.String()
}

func portsText(c *Container) string {
	type pp struct {
		port  int
		proto string
	}
	set := map[pp]bool{}
	if c.Sim != nil {
		for _, st := range labcfg.States {
			for _, p := range c.Sim.Ports[st] {
				set[pp{p.Port, "tcp"}] = true
			}
		}
	}
	for _, s := range c.Services {
		set[pp{s.Port, s.Proto}] = true
	}
	list := make([]pp, 0, len(set))
	for p := range set {
		list = append(list, p)
	}
	sort.Slice(list, func(i, j int) bool {
		return list[i].port < list[j].port || (list[i].port == list[j].port && list[i].proto < list[j].proto)
	})
	if len(list) > 8 {
		return fmt.Sprintf("%d portów TCP (%d–%d)", len(list), list[0].port, list[len(list)-1].port)
	}
	out := make([]string, len(list))
	for i, p := range list {
		out[i] = fmt.Sprintf("%d", p.port)
		if p.proto == "udp" {
			out[i] += "/udp"
		}
	}
	return strings.Join(out, ", ")
}

// AddressPlan renders the Markdown tables of lab/README.md.
func (l *Lab) AddressPlan() string {
	var b strings.Builder
	for _, g := range Groups {
		var rows []Container
		for _, c := range l.Containers {
			if c.Group == g[0] {
				rows = append(rows, c)
			}
		}
		if len(rows) == 0 {
			continue
		}
		fmt.Fprintf(&b, "### %s\n\n| Adres | Kontener | Nazwy DNS | Porty | Stany | Co to jest |\n| --- | --- | --- | --- | --- | --- |\n", g[1])
		for _, c := range rows {
			states := "t0, t1, t2"
			if c.In != nil {
				states = strings.Join(c.In, ", ")
			}
			dns := strings.Join(c.Hostnames, ", ")
			if dns == "" {
				dns = "—"
			}
			ports := portsText(&c)
			if ports == "" {
				ports = "—"
			}
			fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s | %s | %s |\n", c.IP, c.Name, dns, ports, states, c.Desc)
		}
		b.WriteString("\n")
	}
	return b.String()
}
