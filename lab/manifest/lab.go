// New returns the lab manifest with the DNS zone filled in.
func New() *Lab {
	l := &Lab{}
	l.Containers = append(l.Containers, realContainers()...)
	l.Containers = append(l.Containers, simContainers()...)
	for i := range l.Containers {
		c := &l.Containers[i]
		if c.Name == "dns" {
			c.Configs = append(c.Configs, ConfigFile{Target: "/etc/dnsmasq-lab.conf", Content: l.DNSConfig()})
		}
		if c.Sim != nil && c.Avail != nil {
			// labsim needs the availability spec too.
			continue
		}
	}
	sort.SliceStable(l.Containers, func(i, j int) bool {
		a, b := netip.MustParseAddr(l.Containers[i].IP), netip.MustParseAddr(l.Containers[j].IP)
		if a != b {
			return a.Less(b)
		}
		return l.Containers[i].Name < l.Containers[j].Name
	})
	return l
}

// Validate checks the rules the lab must keep.
func (l *Lab) Validate() error {
	prefix := netip.MustParsePrefix(Network)
	names := map[string]bool{}
	for _, c := range l.Containers {
		if names[c.Name] {
			return fmt.Errorf("duplicate container name %s", c.Name)
		}
		names[c.Name] = true
		ip, err := netip.ParseAddr(c.IP)
		if err != nil || !prefix.Contains(ip) {
			return fmt.Errorf("%s: address %q is not in %s", c.Name, c.IP, Network)
		}
		if c.IP == Gateway || c.IP == "10.66.0.0" || c.IP == "10.66.255.255" {
			return fmt.Errorf("%s: address %s is reserved", c.Name, c.IP)
		}
		if c.Image == "" {
			return fmt.Errorf("%s: no image", c.Name)
		}
		if c.Health.Test == "" {
			return fmt.Errorf("%s: no health check", c.Name)
		}
		for _, st := range c.In {
			if !isState(st) {
				return fmt.Errorf("%s: unknown state %q", c.Name, st)
			}
		}
		for _, d := range c.DependsOn {
			if d == c.Name {
				return fmt.Errorf("%s depends on itself", c.Name)
			}
		}
	}
	for _, st := range labcfg.States {
		seen := map[string]string{}
		for _, c := range l.Containers {
			if !c.InState(st) {
				continue
			}
			if other, dup := seen[c.IP]; dup {
				return fmt.Errorf("state %s: %s and %s share %s", st, other, c.Name, c.IP)
			}
			seen[c.IP] = c.Name
		}
	}
	for _, c := range l.Containers {
		for _, d := range c.DependsOn {
			if !names[d] {
				return fmt.Errorf("%s depends on unknown %s", c.Name, d)
			}
		}
	}
	return nil
}

func isState(s string) bool {
	for _, x := range labcfg.States {
		if x == s {
			return true
		}
	}
	return false
}

// DNSConfig is the dnsmasq configuration with the lab zone.
func (l *Lab) DNSConfig() string {
	var b strings.Builder
	b.WriteString("# generated by lab/gen from lab/manifest; do not edit\n")
	b.WriteString("no-resolv\nno-hosts\nno-poll\nuser=root\nlog-facility=-\nlisten-address=0.0.0.0\nbind-interfaces\n")
	b.WriteString("domain=" + Zone + "\nlocal=/" + Zone + "/\nlocal=/66.10.in-addr.arpa/\n")
	seen := map[string]bool{}
	for _, c := range realAndSim(l) {
		for _, fq := range c.FQDNs() {
			if seen[fq] {
				continue
			}
			seen[fq] = true
			b.WriteString("host-record=" + fq + "," + c.IP + "\n")
		}
	}
	return b.String()
}

func realAndSim(l *Lab) []Container {
	out := make([]Container, 0, len(l.Containers))
	for _, c := range l.Containers {
		if !c.NotAHost {
			out = append(out, c)
		}
	}
	return out
}

// SimConfig returns the labsim configuration of an imitation host.
func (c *Container) SimConfig() *labcfg.Host {
	if c.Sim == nil {
		return nil
	}
	h := &labcfg.Host{Name: c.Name, Avail: c.Avail, Firewall: c.Sim.Firewall, States: map[string]labcfg.HostState{}}
	for _, st := range labcfg.States {
		// A labsim container that does not run in a state still gets a
		// configuration for it, so a wrong state file cannot crash it.
		ports := c.Sim.Ports[st]
		hs := labcfg.HostState{}
		for _, p := range ports {
			kind := p.Kind
			if kind == "" {
				kind = "http"
			}
			ln := labcfg.Listener{Port: p.Port, Kind: kind, TLS: p.TLS}
			if kind == "http" {
				site := p.Site
				ln.Site = &site
			}
			hs.Listeners = append(hs.Listeners, ln)
		}
		h.States[st] = hs
	}
	return h
}

var titleRe = regexp.MustCompile(`(?is)<title[^>]*>(.*?)</title>`)

// HTMLTitle extracts the text of the title element the way a scanner shows
// it: entities for spaces decoded, white space collapsed.
func HTMLTitle(body string) string {
	m := titleRe.FindStringSubmatch(body)
	if m == nil {
		return ""
	}
	t := strings.NewReplacer("&nbsp;", " ", "&amp;", "&", "&middot;", "·", "&copy;", "©").Replace(m[1])
	return strings.Join(strings.Fields(t), " ")
}

func findRoute(site *labcfg.Site, path string) *labcfg.Route {
	var fallback *labcfg.Route
	for i := range site.Routes {
		if site.Routes[i].Path == path {
			return &site.Routes[i]
		}
		if site.Routes[i].Path == "*" {
			fallback = &site.Routes[i]
		}
	}
	return fallback
}

func routeStatus(r *labcfg.Route) int {
	switch {
	case r.BasicRealm != "":
		return 401
	case r.Status != 0:
		return r.Status
	case r.Location != "":
		return 302
	}
	return 200
}

// simService derives the truth of one labsim listener.
func simService(c *Container, p SimPort) truth.Service {
	s := truth.Service{
		Port: p.Port, Proto: "tcp", Name: "http", NameAlt: p.NameAlt, Product: p.Product, Version: p.Version, Hard: p.Hard,
		Technologies: p.Techs, TechOptional: p.TechOptional, Classes: p.Classes, ClassOptional: p.ClassOpt,
		Interesting: p.Interesting, Signatures: p.Signatures,
	}
	if p.Kind == "tarpit" {
		s.Name = "unknown"
		return s
	}
	site := p.Site
	h := &truth.HTTP{Server: site.Server, Headers: map[string]string{}}
	r := findRoute(&site, "/")
	if r != nil {
		h.Status = routeStatus(r)
		h.Location = r.Location
		h.Volatile = r.Volatile
		for _, x := range site.Headers {
			h.Headers[x.Name] = x.Value
		}
		for _, x := range r.Headers {
			if strings.Contains(x.Value, "{{") {
				h.Headers[x.Name] = "" // any value: it changes on every request
			} else {
				h.Headers[x.Name] = x.Value
			}
		}
		if r.BasicRealm != "" {
			h.Headers["WWW-Authenticate"] = `Basic realm="` + r.BasicRealm + `"`
		}
		ct := r.ContentType
		var cookies []labcfg.Cookie
		if ct == "" || strings.HasPrefix(ct, "text/html") {
			cookies = append(cookies, site.Cookies...)
		}
		cookies = append(cookies, r.Cookies...)
		for _, ck := range cookies {
			h.Cookies = append(h.Cookies, truth.Cookie{Name: ck.Name, Secure: ck.Secure, HTTPOnly: ck.HTTPOnly, SameSite: strings.ToLower(ck.SameSite), JWT: strings.HasPrefix(ck.Value, "eyJ") && strings.Count(ck.Value, ".") == 2})
		}
		// Follow redirects that stay on this listener to find the landing title.
		land := r
		for hops := 0; hops < 6 && land != nil && land.Location != ""; hops++ {
			if !strings.HasPrefix(land.Location, "/") {
				land = nil
				break
			}
			land = findRoute(&site, land.Location)
		}
		if land != nil {
			h.Title = HTMLTitle(land.Body)
		}
	}
	if len(h.Headers) == 0 {
		h.Headers = nil
	}
	if site.FaviconSeed != "" {
		icon := labcfg.Favicon(site.FaviconSeed)
		m := labcfg.FaviconMMH3(icon)
		h.FaviconMMH3 = &m
		h.FaviconSHA256 = labcfg.FaviconSHA256(icon)
	}
	s.HTTP = h
	if p.TLS != nil {
		s.Tunnel = "ssl"
		t := &truth.TLS{SubjectCN: p.TLS.CN, SANs: p.TLS.SANs, SelfSigned: p.TLS.Mode == "selfsigned", Expired: p.TLS.NotAfterDays < 0, DaysLeft: p.TLS.NotAfterDays, Gen: p.TLS.Gen}
		if p.TLS.Mode == "ca" {
			t.IssuerCN = p.TLS.IssuerCN
			if t.IssuerCN == "" {
				t.IssuerCN = "Czujka Lab Issuing CA"
			}
		} else {
			t.IssuerCN = p.TLS.CN
		}
		t.HostMismatch = true
		for _, name := range append(c.FQDNs(), c.IP) {
			for _, san := range p.TLS.SANs {
				if san == name {
					t.HostMismatch = false
				}
			}
		}
		s.TLS = t
	}
	return s
}

// Truth builds the ground truth of one lab state.
func (l *Lab) Truth(state string) *truth.File {
	f := &truth.File{
		State: state, Network: Network,
		Note:   "Generated by lab/gen from lab/manifest. Do not edit. Unstable hosts carry 'availability'; hard cases carry 'hard'.",
		Ignore: []string{Gateway, ScannerIP},
		Hosts:  []truth.Host{},
	}
	for i := range l.Containers {
		c := &l.Containers[i]
		if c.NotAHost || !c.InState(state) {
			continue
		}
		h := truth.Host{IP: c.IP, Name: c.Name, Hostnames: c.FQDNs(), Group: c.Group, Desc: c.Desc, Availability: c.Avail, Hard: c.Hard, Services: []truth.Service{}}
		if h.Hostnames == nil {
			h.Hostnames = []string{}
		}
		if c.Sim != nil {
			for _, p := range c.Sim.Ports[state] {
				h.Services = append(h.Services, simService(c, p))
			}
		} else {
			h.Services = append(h.Services, c.Services...)
		}
		sort.SliceStable(h.Services, func(a, b int) bool {
			if h.Services[a].Port != h.Services[b].Port {
				return h.Services[a].Port < h.Services[b].Port
			}
			return h.Services[a].Proto < h.Services[b].Proto
		})
		f.Hosts = append(f.Hosts, h)
	}
	return f
}

// StateLists returns, for a state, the compose services to stop and the
// conditional services to start. Services that run in every state are not listed.
func (l *Lab) StateLists(state string) (stop, start []string) {
	for _, c := range l.Containers {
		if c.In == nil {
			continue
		}
		if c.InState(state) {
			start = append(start, c.Name)
		} else {
			stop = append(stop, c.Name)
		}
	}
	sort.Strings(stop)
	sort.Strings(start)
	return stop, start
}
